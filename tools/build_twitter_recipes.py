def build():
    seed = []
    for r in RECIPES:
        seed.append({
            'title': r['title'],
            'servings': r.get('servings', ''),
            'ingredients': [{'name': n, 'amount': a} for n, a in r['ingredients']],
            'steps': r['steps'],
            'tags': [r['tag']],
            'sourceType': 'twitter',
            'sourceUrl': r['url'],
            'creator': CREATOR,
            'memo': r['memo'],
        })
    return seed


def main():
    out = Path(__file__).resolve().parent.parent / 'twitter-recipes.json'
    data = build()
    out.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'{len(data)} recipes written to {out}')


if __name__ == '__main__':
    main()
