def flatten_ingredients(recipe):
    if 'groups' in recipe:
        result = []
        for label, items in recipe['groups']:
            prefix = f'【{label}】' if label else ''
            result.extend({'name': f'{prefix}{n}', 'amount': a} for n, a in items)
        return result
    return [{'name': n, 'amount': a} for n, a in recipe['ingredients']]


def flatten_steps(recipe):
    if 'stepGroups' in recipe:
        result = []
        for label, steps in recipe['stepGroups']:
            result.append(f'――{label}――')
            result.extend(steps)
        return result
    if recipe.get('steps'):
        return recipe['steps']
    return recipe.get('inferred_steps', [])


def build():
    seed = []
    for r in RECIPES:
        memo = r.get('note', '') or ''
        if r.get('inferred_steps') and not r.get('steps'):
            memo = (memo + ' ' + INFERRED_NOTE).strip()
        seed.append({
            'title': r['title'],
            'servings': r.get('servings', ''),
            'ingredients': flatten_ingredients(r),
            'steps': flatten_steps(r),
            'tags': [CAT_LABEL[r['cat']]],
            'sourceType': 'notion',
            'sourceUrl': '',
            'memo': memo,
        })
    return seed


def main():
    out = Path(__file__).resolve().parent.parent / 'seed-recipes.json'
    out.write_text(json.dumps(build(), ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'{len(build())} recipes written to {out}')


if __name__ == '__main__':
    main()
